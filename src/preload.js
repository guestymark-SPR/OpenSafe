'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

async function call(ch, ...args) {
  const r = await ipcRenderer.invoke(ch, ...args);
  if (!r.ok) { const e = new Error(r.error); e.code = r.code; throw e; }
  return r.value;
}

contextBridge.exposeInMainWorld('keep', {
  getData: () => call('data:get'),
  saveAsset: (a) => call('asset:save', a),
  deleteAsset: (id) => call('asset:delete', id),
  duplicateAsset: (id) => call('asset:duplicate', id),
  pickFiles: (assetId, kind, docType) => call('attach:pick', assetId, kind, docType),
  addFiles: (assetId, kind, docType, files) =>
    call('attach:addPaths', assetId, kind, docType, Array.from(files).map(f => webUtils.getPathForFile(f)).filter(Boolean)),
  removeAttachment: (assetId, attId) => call('attach:remove', assetId, attId),
  setCover: (assetId, attId) => call('attach:cover', assetId, attId),
  openAttachment: (assetId, file, name) => call('attach:open', assetId, file, name),
  savePolicy: (p) => call('policy:save', p),
  deletePolicy: (id) => call('policy:delete', id),
  setPolicyItems: (id, ids) => call('policy:setItems', id, ids),
  chooseBackupFolder: () => call('autobackup:chooseFolder'),
  setAutoBackup: (patch) => call('autobackup:set', patch),
  backupNow: () => call('autobackup:runNow'),
  setTheme: (t) => call('theme:set', t),
  security: () => call('sec:state'),
  enableProtection: (pw) => call('sec:enable', pw),
  unlock: (pw) => call('sec:unlock', pw),
  recover: (rk, pw) => call('sec:recover', rk, pw),
  changePassword: (cur, next) => call('sec:changePassword', cur, next),
  newRecoveryKey: (pw) => call('sec:newRecovery', pw),
  disableProtection: (pw) => call('sec:disable', pw),
  lock: () => call('sec:lock'),
  saveRecoveryKey: (rk) => call('sec:saveRecovery', rk),
  copyText: (t) => call('clip:copy', t),
  vaultSetup: (pin) => call('vault:setup', pin),
  vaultUnlock: (pin) => call('vault:unlock', pin),
  vaultLock: () => call('vault:lock'),
  vaultChangePin: (cur, next) => call('vault:changePin', cur, next),
  vaultRecoverPin: (rk, pin) => call('vault:recoverPin', rk, pin),
  vaultRemove: () => call('vault:remove'),
  vaultMoveItem: (id, to) => call('vault:moveItem', id, to),
  vaultMoveFile: (assetId, attId, to) => call('vault:moveFile', assetId, attId, to),
  onSecurity: (fn) => ipcRenderer.on('security:changed', (_e, st) => fn(st)),
  saveService: (assetId, entry) => call('service:save', assetId, entry),
  deleteService: (assetId, id) => call('service:delete', assetId, id),
  updateSettings: (patch) => call('settings:update', patch),
  setLists: (cats, locs) => call('lists:set', cats, locs),
  exportCsv: () => call('export:csv'),
  exportReport: (opts) => call('export:report', opts),
  backup: () => call('backup:create'),
  restore: () => call('backup:restore'),
  openDataFolder: () => call('data:openFolder'),
  importPick: () => call('import:pick'),
  importFiles: (files) => call('import:paths', Array.from(files).map(f => webUtils.getPathForFile(f)).filter(Boolean)),
  captureInfo: () => call('capture:info'),
  openCapture: () => call('open:external', 'capture'),
  phoneStatus: () => call('phone:status'),
  phoneEnable: (on) => call('phone:enable', on),
  phoneReset: () => call('phone:reset'),
  fixFirewall: () => call('phone:fixFirewall'),
  firewallRule: () => call('phone:firewallRule'),
  updateStatus: () => call('update:status'),
  checkForUpdates: () => call('update:check'),
  installUpdate: () => call('update:install'),
  onUpdate: (fn) => ipcRenderer.on('update:status', (_e, st) => fn(st)),
  onChanged: (fn) => ipcRenderer.on('data:changed', () => fn()),
  onNav: (fn) => ipcRenderer.on('nav', (_e, where) => fn(where))
});
